import React from 'react';
import { Button } from '@/components/ui/button';
import { Copy, Download } from 'lucide-react';

export default function CodeExport({ chatbot, onCopy }) {
  const pythonCode = `"""
RAG Chatbot: ${chatbot.title}
Generated by RAG Mentor

Description: ${chatbot.description}

This code uses LangChain to implement a RAG pipeline.
Install dependencies: pip install langchain openai faiss-cpu python-dotenv
"""

import os
from dotenv import load_dotenv
from langchain.document_loaders import PyPDFLoader, TextLoader
from langchain.text_splitter import RecursiveCharacterTextSplitter
from langchain.embeddings import OpenAIEmbeddings
from langchain.vectorstores import FAISS
from langchain.chat_models import ChatOpenAI
from langchain.chains import RetrievalQA
from langchain.prompts import PromptTemplate

# Load environment variables
load_dotenv()
OPENAI_API_KEY = os.getenv("OPENAI_API_KEY")

# Step 1: Load documents
documents = []
# TODO: Add your document loading logic here
# Example:
# loader = PyPDFLoader("path/to/your/document.pdf")
# documents = loader.load()

# Step 2: Split text into chunks
text_splitter = RecursiveCharacterTextSplitter(
    chunk_size=${chatbot.nodes.find(n => n.type === 'TextSplitter')?.params?.chunk_size || 1000},
    chunk_overlap=${chatbot.nodes.find(n => n.type === 'TextSplitter')?.params?.overlap || 200}
)
texts = text_splitter.split_documents(documents)

# Step 3: Create embeddings
embeddings = OpenAIEmbeddings(
    model="${chatbot.nodes.find(n => n.type === 'Embeddings')?.params?.model || 'text-embedding-ada-002'}"
)

# Step 4: Create vector store
# For AMD ROCm acceleration, consider using hipVS or ROCm-optimized FAISS
vectorstore = FAISS.from_documents(texts, embeddings)

# Step 5: Create LLM
llm = ChatOpenAI(
    model_name="${chatbot.nodes.find(n => n.type === 'LLM')?.params?.model || 'gpt-3.5-turbo'}",
    temperature=${chatbot.nodes.find(n => n.type === 'LLM')?.params?.temperature || 0.7}
)

# AMD Integration Note:
# To run on AMD hardware with ROCm:
# 1. Install ROCm: https://rocm.docs.amd.com/
# 2. Use AMD-optimized models with Ollama or vLLM
# 3. Replace OpenAI embeddings with local models
# 4. Use hipVS for faster vector search

# Step 6: Create retrieval QA chain
qa_chain = RetrievalQA.from_chain_type(
    llm=llm,
    chain_type="stuff",
    retriever=vectorstore.as_retriever(search_kwargs={"k": 3}),
    return_source_documents=True
)

# Step 7: Query the chatbot
def chat(question: str):
    """
    Ask a question to the chatbot
    """
    result = qa_chain({"query": question})
    return {
        "answer": result["result"],
        "source_documents": result["source_documents"],
        "confidence": calculate_confidence(result)  # Custom implementation
    }

def calculate_confidence(result):
    """
    Calculate confidence score based on retrieval quality
    """
    # Simple heuristic - implement your own logic
    if len(result.get("source_documents", [])) > 0:
        return 0.8
    return 0.3

# Example usage
if __name__ == "__main__":
    while True:
        question = input("You: ")
        if question.lower() in ["exit", "quit"]:
            break
        
        response = chat(question)
        print(f"Bot: {response['answer']}")
        print(f"Confidence: {response['confidence']:.2f}")
        print()
`;

  const handleDownload = () => {
    const blob = new Blob([pythonCode], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${chatbot.title.toLowerCase().replace(/\s+/g, '_')}_rag.py`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-4">
      <div className="flex items-center justify-between">
        <h3 className="font-semibold">Python Code (LangChain)</h3>
        <div className="flex gap-2">
          <Button variant="outline" size="sm" onClick={() => onCopy(pythonCode)}>
            <Copy className="w-4 h-4 mr-2" />
            Copy
          </Button>
          <Button variant="outline" size="sm" onClick={handleDownload}>
            <Download className="w-4 h-4 mr-2" />
            Download
          </Button>
        </div>
      </div>

      <pre className="bg-slate-900 text-slate-100 p-4 rounded-lg text-xs overflow-x-auto max-h-96">
        {pythonCode}
      </pre>

      <div className="bg-amber-50 border border-amber-200 rounded-lg p-4">
        <h4 className="font-semibold text-sm mb-2">🚀 Self-Hosting Instructions:</h4>
        <ol className="text-sm space-y-1 list-decimal list-inside">
          <li>Download the Python code above</li>
          <li>Install dependencies: <code className="bg-amber-100 px-1 rounded">pip install langchain openai faiss-cpu</code></li>
          <li>Add your documents to the loader section</li>
          <li>Set your OpenAI API key in a <code className="bg-amber-100 px-1 rounded">.env</code> file</li>
          <li>Run: <code className="bg-amber-100 px-1 rounded">python your_file.py</code></li>
        </ol>
      </div>
    </div>
  );
}