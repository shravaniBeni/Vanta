-- =============================================================================
-- Vanta Platform — 002_rls.sql
-- Row Level Security policies.
-- Run AFTER 001_schema.sql.
--
-- Design principles applied here:
--
-- 1. Authenticated users can only access their own rows.
-- 2. No anonymous/public SELECT policy for rag_apps — public embed access
--    is mediated exclusively by the Express API using embed_id + service role.
-- 3. No anonymous INSERT policy for messages — all message inserts go through
--    the Express API which validates deployed status before inserting.
-- 4. The Express server uses the SERVICE ROLE KEY which bypasses RLS entirely.
--    These policies protect direct Supabase client access only.
-- =============================================================================


-- ── profiles ──────────────────────────────────────────────────────────────

ALTER TABLE profiles ENABLE ROW LEVEL SECURITY;

-- Users can read their own profile.
CREATE POLICY "profiles: owner select"
  ON profiles
  FOR SELECT
  USING (id = auth.uid());

-- Users can update their own profile.
CREATE POLICY "profiles: owner update"
  ON profiles
  FOR UPDATE
  USING (id = auth.uid());

-- Insert is handled exclusively by the handle_new_user() trigger (SECURITY DEFINER).
-- No manual INSERT policy needed.


-- ── projects ──────────────────────────────────────────────────────────────

ALTER TABLE projects ENABLE ROW LEVEL SECURITY;

-- Users can perform all operations on their own projects.
CREATE POLICY "projects: owner all"
  ON projects
  FOR ALL
  USING (user_id = auth.uid());


-- ── rag_apps ──────────────────────────────────────────────────────────────

ALTER TABLE rag_apps ENABLE ROW LEVEL SECURITY;

-- Users can perform all operations on their own RAG apps.
CREATE POLICY "rag_apps: owner all"
  ON rag_apps
  FOR ALL
  USING (user_id = auth.uid());

-- No anonymous SELECT policy.
-- Public embed access (Chat widget) is handled by the Express API using the
-- service role key, which bypasses RLS. The route validates embed_id and
-- returns only the fields required by the public chat widget.


