-- ── messages ──────────────────────────────────────────────────────────────

ALTER TABLE messages ENABLE ROW LEVEL SECURITY;

-- Authenticated users can read messages belonging to their own RAG apps.
CREATE POLICY "messages: owner select"
  ON messages
  FOR SELECT
  USING (
    user_id = auth.uid()
    OR EXISTS (
      SELECT 1 FROM rag_apps
      WHERE rag_apps.id = messages.rag_app_id
        AND rag_apps.user_id = auth.uid()
    )
  );

-- No anonymous INSERT policy.
-- All inserts (including from anonymous embed users) go through the Express
-- API which uses the service role key and validates that the target rag_app
-- has status = 'deployed' before inserting.


