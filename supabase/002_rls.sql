-- =============================================================================
-- Supabase Storage: knowledge-docs bucket
-- The bucket itself is created manually in the Supabase dashboard (see README).
-- Storage policies below restrict access to authenticated owners only.
-- No public access is permitted.
-- Signed URLs are generated by the Express API only on explicit authenticated
-- request (POST /api/documents/:id/signed-url).
-- =============================================================================

-- Allow authenticated users to upload to their own path prefix.
CREATE POLICY "storage: owner insert"
  ON storage.objects
  FOR INSERT
  TO authenticated
  WITH CHECK (
    bucket_id = 'knowledge-docs'
    AND (storage.foldername(name))[1] = auth.uid()::text
  );

-- Allow authenticated users to read their own files.
CREATE POLICY "storage: owner select"
  ON storage.objects
  FOR SELECT
  TO authenticated
  USING (
    bucket_id = 'knowledge-docs'
    AND (storage.foldername(name))[1] = auth.uid()::text
  );

-- Allow authenticated users to delete their own files.
CREATE POLICY "storage: owner delete"
  ON storage.objects
  FOR DELETE
  TO authenticated
  USING (
    bucket_id = 'knowledge-docs'
    AND (storage.foldername(name))[1] = auth.uid()::text
  );

-- Note: The Express server uses the service role key for all storage
-- operations (upload, signed URL generation, deletion) and bypasses
-- these storage policies. The policies above are a defence-in-depth
-- layer for any future direct browser storage access.
